def osrm(route):
    pts = [[NEG[1], NEG[0]], [-74.4275, 9.2405], [-74.4290, 9.2380], [-74.4310, 9.2362], [-74.4322, 9.2341], [-74.4331, 9.2330], [CLI[1], CLI[0]]]
    route.fulfill(status=200, content_type="application/json", body=json.dumps({"code": "Ok", "routes": [{"distance": 1460, "duration": 290, "geometry": {"type": "LineString", "coordinates": pts}}]}))
def nomi(route):
    u = route.request.url
    if "/reverse" in u: body = {"address": {"road": "Carrera 3", "house_number": "18-40", "neighbourhood": "Barrio Santa Bárbara"}}
    else: body = [{"lat": str(CLI[0]), "lon": str(CLI[1]), "display_name": "Santa Bárbara, Mompox"}]
    route.fulfill(status=200, content_type="application/json", body=json.dumps(body))
